const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const prices=JSON.parse(fs.readFileSync(path.join(root,"data/prices.json"),"utf8"));
const context=vm.createContext({document:{addEventListener(){}},prices,console});
vm.runInContext(fs.readFileSync(path.join(root,"assets/app.js"),"utf8"),context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('marketDateLabel({NVDA:{date:"2026-10-12"},TSLA:{date:"2026-10-12"}},["NVDA","TSLA"])'),"2026.10.12");
assert.equal(run('marketDateLabel({NVDA:{date:"2026-10-12"},TSLA:{date:"2026-10-09"}},["NVDA","TSLA"])'),"NVDA 10/12 · TSLA 10/09");
assert.equal(run('marketDateLabel({NVDA:{date:"2026-10-12"}},["NVDA","TSLA"])'),"NVDA 10/12 · TSLA 미확인");
assert.equal(run('marketDateLabel({},["NVDA","TSLA"])'),"미확인");
assert.equal(run('bitcoinCloseLabel("2026-10-12")'),"2026.10.13 09:00 KST");
assert.equal(run('bitcoinCloseLabel("2026-12-31")'),"2027.01.01 09:00 KST");
assert.equal(run('bitcoinCloseLabel("2026-02-30")'),"미확인");
assert.equal(run('dataUpdateLabel("2026-10-13T09:11:41Z")'),"데이터 갱신 2026.10.13 18:11 KST");
assert.equal(run('dataUpdateLabel(null)'),"갱신 시각 미확인");
const original=JSON.stringify(prices);
run('marketDateLabel(prices.markets,["NVDA","TSLA","AMZN","GOOGL"]);bitcoinCloseLabel(prices.markets["KRW-BTC"].date);dataUpdateLabel(prices.updatedAt)');
assert.equal(JSON.stringify(prices),original);
console.log("header dates: shared, mixed, missing, BTC rollover, KST timestamp and data preservation passed");
